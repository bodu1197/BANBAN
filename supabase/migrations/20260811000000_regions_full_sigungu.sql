-- 삭제는 하지 않는다: 적용 시점의 운영 DB 133행은 이 목록의 부분집합이라 지울 행이 없었고,
--       artists.region_id 가 참조하는 행을 지우면 샵이 지역에서 사라진다.
-- 멱등: name 유니크 인덱스 + on conflict 로 재실행·동시실행해도 중복행이 생기지 않는다.

